#!/usr/bin/env python3
"""Compile SnapFrame GLSL compute shaders into a C++ SPIR-V header.

Requires glslangValidator and spirv-val on the host. This runs before the
Android NDK build; the Android build itself does not need shader compiler tools.
"""
import argparse
import os
import pathlib
import shutil
import struct
import subprocess
import sys
import tempfile


ROOT = pathlib.Path(__file__).resolve().parents[1]
SHADER_DIR = ROOT / "android/app/jni/snapframe/shaders"
DEFAULT_OUTPUT = ROOT / "android/app/jni/snapframe/generated/snapframe_shaders.h"
SHADERS = [
    ("luma_downsample", SHADER_DIR / "luma_downsample.comp"),
    ("block_match_flow", SHADER_DIR / "block_match_flow.comp"),
    ("flow_consistency", SHADER_DIR / "flow_consistency.comp"),
]


def find_tool(explicit, env_name, executable):
    candidate = explicit or os.environ.get(env_name) or shutil.which(executable)
    if not candidate:
        raise RuntimeError(
            f"{executable} not found; install the Vulkan shader tools or set {env_name}"
        )
    return candidate


def compile_one(compiler, validator, source, output):
    subprocess.run([
        compiler, "-V", "--target-env", "vulkan1.1", "-S", "comp",
        "-o", str(output), str(source)
    ], check=True)
    subprocess.run([
        validator, "--target-env", "vulkan1.1", str(output)
    ], check=True)

    data = output.read_bytes()
    if len(data) == 0 or len(data) % 4:
        raise RuntimeError(f"{source.name}: invalid SPIR-V byte length {len(data)}")
    words = struct.unpack("<" + "I" * (len(data) // 4), data)
    if words[0] != 0x07230203:
        raise RuntimeError(f"{source.name}: invalid SPIR-V magic")
    return words


def write_header(path, compiled):
    lines = [
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "// Generated by tools/compile_snapframe_shaders.py; do not edit.",
        "namespace snapframe {",
        "namespace shaders {",
        "",
    ]
    for name, words in compiled:
        lines.append(f"alignas(4) static constexpr uint32_t k_{name}[] = {{")
        for i in range(0, len(words), 8):
            chunk = words[i:i + 8]
            lines.append("    " + ", ".join(f"0x{word:08x}u" for word in chunk) + ",")
        lines.extend([
            "};",
            f"static constexpr uint32_t k_{name}_word_count =",
            f"    uint32_t(sizeof(k_{name}) / sizeof(k_{name}[0]));",
            "",
        ])
    lines.extend(["} // namespace shaders", "} // namespace snapframe", ""])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--glslang", help="path to glslangValidator")
    parser.add_argument("--spirv-val", help="path to spirv-val")
    parser.add_argument("--output", type=pathlib.Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    compiler = find_tool(args.glslang, "GLSLANG_VALIDATOR", "glslangValidator")
    validator = find_tool(args.spirv_val, "SPIRV_VAL", "spirv-val")

    compiled = []
    with tempfile.TemporaryDirectory(prefix="snapframe-spv-") as temp:
        temp_dir = pathlib.Path(temp)
        for name, source in SHADERS:
            if not source.is_file():
                raise RuntimeError(f"shader source missing: {source}")
            output = temp_dir / f"{name}.spv"
            words = compile_one(compiler, validator, source, output)
            compiled.append((name, words))

    write_header(args.output, compiled)
    print(f"SnapFrame: generated {args.output} ({len(compiled)} shader(s))")


if __name__ == "__main__":
    try:
        main()
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"SnapFrame shader build failed: {error}", file=sys.stderr)
        sys.exit(1)
